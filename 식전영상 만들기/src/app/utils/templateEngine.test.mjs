import assert from 'node:assert/strict';
import * as m from './templateEngine.test-build.js';
let p=m.newProject('테스트');assert.equal(p.name,'테스트');
let s=m.newScene('첫 장면');assert.equal(s.scene.duration,5);
p=m.addScene(p,s);assert.equal(p.scenes.length,1);
p=m.duplicateScene(p,s.id);assert.equal(p.scenes.length,2);assert.notEqual(p.scenes[0].id,p.scenes[1].id);
p=m.removeScene(p,p.scenes[1].id);assert.equal(p.scenes.length,1);
p=m.addScene(p,m.newScene('둘째'));p=m.moveScene(p,0,1);assert.equal(p.scenes[1].name,'첫 장면');
s=m.renameScene(s,'수정');assert.equal(s.name,'수정');
s=m.setSceneDuration(s,9);assert.equal(s.scene.duration,9);
s=m.setSceneTransition(s,'zoom');assert.equal(s.scene.transition,'zoom');
s=m.setTransitionDuration(s,1.2);assert.equal(s.scene.transitionDuration,1.2);
s=m.setSceneVolume(s,2);assert.equal(s.scene.musicVolume,1);
const layer={id:'a',type:'text',x:0,y:0,w:30,h:20,rotation:0,opacity:1,text:'원본'};
s=m.addLayer(s,layer);assert.equal(s.elements.length,1);
s=m.duplicateLayer(s,'a');assert.equal(s.elements.length,2);assert.notEqual(s.elements[0].id,s.elements[1].id);
s=m.removeLayer(s,s.elements[1].id);assert.equal(s.elements.length,1);
s=m.addLayer(s,{...layer,id:'b',type:'photo_zone'});s=m.moveLayer(s,0,1);assert.equal(s.elements[1].id,'a');
s=m.updateLayer(s,'a',{text:'수정'});assert.equal(s.elements[1].text,'수정');
s=m.setLayerPosition(s,'a',120,-3);assert.equal(s.elements[1].x,100);assert.equal(s.elements[1].y,0);
s=m.setLayerSize(s,'a',0,150);assert.equal(s.elements[1].w,1);assert.equal(s.elements[1].h,100);
s=m.setLayerRotation(s,'a',-90);assert.equal(s.elements[1].rotation,270);
s=m.setLayerOpacity(s,'a',2);assert.equal(s.elements[1].opacity,1);
s=m.setLayerAnimation(s,'a','fade-in',2,1);assert.equal(s.elements[1].animation.effect,'fade-in');
s=m.toggleLayerLock(s,'a');assert.equal(s.elements[1].locked,true);assert.equal(m.updateLayer(s,'a',{text:'잠금'}).elements[1].text,'수정');
s=m.toggleLayerVisibility(s,'a');assert.equal(s.elements[1].hidden,true);
s=m.setBackgroundColor(s,'#123456');assert.equal(s.bg.color,'#123456');
assert.equal(m.listPhotoZones(s).length,1);assert.equal(m.listEditableText(s).length,1);
p=m.addScene(m.newProject(),s);assert.equal(m.totalDuration(p),9);
s=m.applyCustomerText(s,{a:'신랑 신부'});assert.equal(s.elements[1].text,'신랑 신부');
assert.deepEqual(m.validateProject(p),[]);
const serialized=m.serializeProject(p);assert.equal(m.parseProject(serialized).scenes.length,1);
assert.throws(()=>m.parseProject('{bad'));
assert.ok(m.validateProject({...p,scenes:[s,s]}).length>0);
console.log('PASS: 31 template operations and validation assertions');
